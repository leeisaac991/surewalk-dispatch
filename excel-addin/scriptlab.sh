#!/usr/bin/env bash
# Build the Script Lab snippet: the whole dispatch panel (same code as the Edge extension and the add-in) in one file
# that you import into Script Lab in Excel. No hosting, no manifest.
#   ./scriptlab.sh            -> scriptlab/SURE-Walk-Dispatch.yaml   (+ scriptlab/preview.html, the same page for testing)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"; SRC="$HERE/../edge-extension"; OUT="$HERE/scriptlab"
mkdir -p "$OUT"
python3 - "$SRC" "$OUT" <<'PY'
import re, sys, os
src, out = sys.argv[1], sys.argv[2]
html = open(os.path.join(src, 'panel.html')).read()
body = re.search(r'<body>(.*?)</body>', html, re.S).group(1)
body = re.sub(r'\s*<script[^>]*></script>', '', body).strip() + '\n'
css = open(os.path.join(src, 'panel.css')).read()
parts = ['lib/office-host.js', 'lib/places.js', 'lib/rules.js', 'lib/excel.js', 'lib/groupme.js', 'panel.js']
js = '\n'.join(f'/* ---- {p} ---- */\n' + open(os.path.join(src, p)).read() for p in parts)
js = '// @ts-nocheck\n// SURE Walk Dispatch — generated by excel-addin/scriptlab.sh from edge-extension/. Edit those files, not this.\n' + js
def block(s, n=4):
    pad = ' ' * n
    return '\n'.join(pad + l if l.strip() else '' for l in s.rstrip('\n').split('\n')) + '\n'
yaml = ('name: SURE Walk Dispatch\n'
        'description: Dispatch panel for the SURE Walk rides sheet (assign, at, picked, cancel, GroupMe posts).\n'
        'host: EXCEL\napi_set: {}\n'
        'script:\n  content: |\n' + block(js) + '  language: typescript\n'
        'template:\n  content: |\n' + block(body) + '  language: html\n'
        'style:\n  content: |\n' + block(css) + '  language: css\n'
        'libraries: |\n    https://appsforoffice.microsoft.com/lib/1/hosted/office.js\n    @types/office-js\n')
open(os.path.join(out, 'SURE-Walk-Dispatch.yaml'), 'w').write(yaml)
# The same page as one HTML file (what Script Lab runs), for local testing with a fake Office.js.
page = ('<!DOCTYPE html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">'
        '<script src="https://appsforoffice.microsoft.com/lib/1/hosted/office.js"></script>'
        f'<style>{css}</style></head><body>{body}<script>{js}</script></body></html>')
open(os.path.join(out, 'preview.html'), 'w').write(page)
print('snippet:', os.path.join(out, 'SURE-Walk-Dispatch.yaml'), f'({len(yaml)//1024} KB)')
PY
